import { test, expect } from "@playwright/test";
import type { Score } from "../../src/model";

test("write a bass-clef cantus from scratch and use it for counterpoint", async ({ page }) => {
  await page.goto("/");
  await expect(page.locator(".engraving svg")).toBeVisible();
  await page.locator(".exercise-setup > summary").click();
  await page.getByLabel("Cantus clef", { exact: true }).selectOption("bass");
  await page.getByLabel("Starting cantus mode").selectOption("Ionian");
  await page.getByRole("button", { name: "Start from scratch" }).click();
  await expect(page.getByRole("heading", { name: "Write a cantus firmus" })).toBeVisible();
  await expect(page.locator(".exercise-setup")).not.toHaveAttribute("open", "");
  await expect(page.locator(".cantus-settings")).not.toHaveAttribute("open", "");
  await page.locator(".cantus-settings > summary").click();
  const modeBox = await page.getByLabel("Cantus mode", { exact: true }).boundingBox();
  const clefBox = await page.getByLabel("Edit cantus clef").boundingBox();
  expect(Math.abs(modeBox!.width - clefBox!.width)).toBeLessThan(1);
  const speciesBox = await page.getByLabel("Counterpoint species").boundingBox();
  const voicesBox = await page.getByLabel("Counterpoint voices").boundingBox();
  expect(Math.abs(speciesBox!.width - voicesBox!.width)).toBeLessThan(1);
  expect(Math.abs(speciesBox!.x - modeBox!.x)).toBeLessThan(1);
  await expect(page.getByRole("button", { name: "Sample answer", exact: true })).toHaveCount(0);
  await expect(page.getByRole("button", { name: "Write counterpoint" })).toBeDisabled();
  await expect(page.getByText("8 measures still need a whole note.")).toBeVisible();
  await page.getByRole("button", { name: "Go to next incomplete measure" }).click();
  await expect(page.locator('[data-note="v1n0"]')).toHaveAttribute("fill", "var(--selection)");
  await page.getByRole("button", { name: "Add measure" }).click();
  await expect(page.getByText("9 measures", { exact: true })).toBeVisible();
  await page.locator('[aria-label="Score editor"]').focus();
  for (const key of ["d", "e", "f", "g", "a", "g", "f", "e", "d"]) await page.keyboard.press(key);
  const draft = async (): Promise<Score> => page.evaluate(() => JSON.parse(localStorage.getItem("gradus-recovery")!));
  await expect.poll(async () => (await draft()).voices[0].notes.filter(n => n.pitch).length).toBe(9);
  const original = await draft();
  expect(original.clefs).toEqual(["bass"]);
  expect(original.mode).toBe("Ionian");
  await page.getByLabel("Cantus mode", { exact: true }).selectOption("Dorian");
  await expect.poll(async () => (await draft()).mode).toBe("Dorian");
  expect((await draft()).voices[0].notes.map(n => n.pitch)).toEqual(original.voices[0].notes.map(n => n.pitch));
  await page.getByLabel("Edit cantus clef").selectOption("alto");
  await expect.poll(async () => (await draft()).clefs?.[0]).toBe("alto");
  expect((await draft()).voices[0].notes.map(n => n.pitch)).toEqual(original.voices[0].notes.map(n => n.pitch));
  await page.getByLabel("Edit cantus clef").selectOption("bass");
  await page.getByLabel("Counterpoint species").selectOption("2");
  await page.getByLabel("Counterpoint voices").selectOption("2");
  await page.getByLabel("Cantus placement").selectOption("0");
  await page.getByRole("button", { name: "Write counterpoint" }).click();
  const result = await draft();
  expect(result.cantusOnly).toBe(false);
  expect(result.species).toBe(2);
  expect(result.mode).toBe("Dorian");
  expect(result.voices[0].locked).toBe(true);
  expect(result.voices[0].notes.map(n => n.pitch)).toEqual(original.voices[0].notes.map(n => n.pitch));
  expect(result.clefs?.[0]).toBe("bass");
  expect(result.voices[1].locked).toBe(false);
  await page.reload();
  await expect.poll(async () => (await draft()).id).toBe(result.id);
});
