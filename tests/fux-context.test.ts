const P = (s: string): Pitch => ({
  step: s[0],
  alter: s.includes("#") ? 1 : s.includes("b") ? -1 : 0,
  octave: Number(s.at(-1)),
});
function exercise(species = 3, count = 2): Score {
  return {
    version: 1,
    id: "independent-fixture",
    title: "Manually specified local figure",
    mode: "Ionian",
    species,
    bars: 5,
    voices: Array.from({ length: count }, (_, vi) => ({
      id: `v${vi}`,
      name: `Voice ${vi + 1}`,
      locked: vi === count - 1,
      species: vi === count - 1 ? 1 : species,
      notes: Array.from({ length: vi === count - 1 ? 5 : 17 }, (_, i) => ({
        id: `v${vi}n${vi === count - 1 ? i * 8 : i * 2}`,
        time: vi === count - 1 ? i * 8 : i * 2,
        duration: vi === count - 1 || i === 16 ? 8 : 2,
        pitch: vi === count - 1 ? P("C4") : null,
      })),
    })),
  };
}
function put(s: Score, time: number, value: string, vi = 0) {
  s.voices[vi].notes.find((n) => n.time === time)!.pitch = P(value);
}
function atError(s: Score, id: string) {
  return check(s).filter((f) => f.severity === "error" && f.notes.includes(id));
}
function historicalScore(id: string) {
  const rows = JSON.parse(fs.readFileSync("public/sources/fux.json", "utf8"));
  return parseKern(rows.find((r: any) => r.metadata.id === id));
}

// Expected local judgments below are specified from the cited musical figures,
// rather than generated by a solver and then used as that solver's own oracle.
function wholeNoteExercise(count = 2) {
  const s = exercise(1, count);
  for (const v of s.voices) {
    v.notes = v.notes.filter((n) => n.time % 8 === 0);
    for (const n of v.notes) n.duration = 8;
  }
  return s;
}
test("adjacent C sharp and C natural in different first-species voices are a cross-relation", () => {
  const s = wholeNoteExercise(3);
  s.mode = "Aeolian";
  s.voices[1].locked = true;
  s.voices[2].locked = false;
  put(s, 0, "C#5");
  put(s, 0, "A3", 1);
  put(s, 0, "A2", 2);
  put(s, 8, "A4");
  put(s, 8, "C4", 1);
  put(s, 8, "A2", 2);
  const relations = () => check(s).filter((f) => f.rule === "cross-relation");
  expect(relations()).toEqual([expect.objectContaining({
    severity: "error",
    notes: ["v0n0", "v1n8"],
  })]);
  put(s, 0, "C5");
  expect(relations()).toEqual([]);
});
