test("screenshot G–F–E–D over held B retains the Fux consonant-anchor requirement", () => {
  const s = exercise(3, 3);
  // The middle voice is still unwritten, as in an unfinished exercise.
  for (const n of s.voices[2].notes) n.pitch = P("B2");
  for (const [i, pitch] of ["G5", "F5", "E5", "D5"].entries())
    put(s, 24 + i * 2, pitch);
  const findings = check(s).filter((f) => f.rule === "dissonance");
  for (const time of [26, 28]) {
    const f = findings.find((f) => f.notes.includes(`v0n${time}`))!;
    expect(f).toBeDefined();
    expect(f.notes).toContain("v2n24");
    const text = violationText(s, f);
    expect(text).toContain(`Voice 1's ${time === 26 ? "F5" : "E5"}`);
    expect(text).toContain("Voice 3's held B2");
    expect(text).toContain("does not need to approach or leave by step here");
  }
  // With C in the bass, F is a supported passing fourth between G and E.
  s.voices[2].notes.find((n) => n.time === 24)!.pitch = P("C3");
  expect(check(s).filter((f) => f.rule === "dissonance")).toEqual([]);
});
